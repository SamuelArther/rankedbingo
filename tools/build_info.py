"""Builds js/info-data.js (ranks, pay, fitness, eligibility, bases, history,
famous people and slang) from the research files.

Usage: python tools/build_info.py <research folder>
"""
import json
import sys
from pathlib import Path


def build(folder):
    folder = Path(folder)
    ranks_pay = json.loads((folder / "ranks_pay.json").read_text(encoding="utf-8"))
    fit = json.loads((folder / "fitness_eligibility.json").read_text(encoding="utf-8"))
    bhp = json.loads((folder / "bases_history_people.json").read_text(encoding="utf-8"))
    pay = ranks_pay["pay"]
    info = {
        "ranks": ranks_pay["ranks"],
        "levelNotes": ranks_pay["levelNotes"],
        "pay": {
            "year": pay["year"], "raisePercent": pay["raisePercent"], "effective": pay["effective"],
            "source": pay["source"], "yos": pay["yos"], "table": pay["table"],
            "e1Under4Months": pay["e1Under4Months"], "notes": pay["notes"], "allowances": pay["allowances"],
        },
        "fitness": fit["fitness"],
        "eligibility": fit["eligibility"],
        "eligibilityGeneral": fit.get("general", []),
        "bases": bhp["bases"],
        "history": bhp["history"],
        "people": bhp["people"],
        "slang": bhp["slang"],
        "asOf": "2026-10-21",
    }
    body = json.dumps(info, ensure_ascii=False, separators=(",", ":"))
    target = Path(__file__).resolve().parent.parent / "js" / "info-data.js"
    target.write_text(
        '"use strict";\n// Generated by tools/build_info.py from research against official sources. Do not edit by hand.\n'
        f"window.INFO = {body};\n",
        encoding="utf-8",
    )
    print(f"wrote {target} ({target.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    build(sys.argv[1])
