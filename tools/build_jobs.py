"""Builds js/jobs-data.js from the per-branch job research files.

Usage: python tools/build_jobs.py <folder with jobs_<branch>.json files>

Each input file looks like {"branch": "army", "jobs": [{"code", "title",
"track", "category", "description", "training", "source", "unverified"?}]}.
"""
import json
import re
import sys
from pathlib import Path

BRANCHES = ["army", "usmc", "navy", "af", "sf", "cg"]
TRACKS = {"enlisted", "warrant", "officer"}


def slug(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def clean(text):
    return re.sub(r"\s+", " ", str(text or "")).strip()


def build(folder):
    out = {}
    for branch in BRANCHES:
        path = Path(folder) / f"jobs_{branch}.json"
        if not path.exists():
            print(f"{branch}: no file, skipped")
            continue
        data = json.loads(path.read_text(encoding="utf-8"))
        jobs, seen = [], set()
        for raw in data.get("jobs", []):
            title = clean(raw.get("title"))
            track = clean(raw.get("track")).lower()
            if not title or track not in TRACKS:
                continue
            # Skip jobs nobody can start in (senior-only codes), when marked.
            if raw.get("entryLevel") is False:
                continue
            code = clean(raw.get("code")) or None
            # Only exact repeats are dropped; different jobs can share a code.
            if (title.lower(), track) in seen:
                continue
            seen.add((title.lower(), track))
            # Ids must be unique per branch: the code when it's free, otherwise
            # code plus title (and the track as a last resort).
            used = {j["id"] for j in jobs}
            job_id = slug(code or title)
            if job_id in used:
                job_id = slug(f"{code or ''} {title}")
            if job_id in used:
                job_id = f"{job_id}-{track}"
            job = {
                "id": job_id,
                "code": code,
                "title": title,
                "track": track,
                "category": clean(raw.get("category")) or "Other",
                "description": clean(raw.get("description")),
            }
            if clean(raw.get("training")):
                job["training"] = clean(raw.get("training"))
            if clean(raw.get("source")).startswith("http"):
                job["source"] = clean(raw.get("source"))
            if raw.get("unverified"):
                job["unverified"] = True
            jobs.append(job)
        jobs.sort(key=lambda j: (j["category"].lower(), j["code"] or "", j["title"]))
        out[branch] = jobs
        counts = {t: sum(j["track"] == t for j in jobs) for t in ("enlisted", "warrant", "officer")}
        print(f"{branch}: {len(jobs)} jobs {counts}")
    body = json.dumps(out, ensure_ascii=False, separators=(",", ":"))
    target = Path(__file__).resolve().parent.parent / "js" / "jobs-data.js"
    target.write_text(
        '"use strict";\n// Generated by tools/build_jobs.py from official career listings. Do not edit by hand.\n'
        f"window.FULL_JOBS = {body};\n",
        encoding="utf-8",
    )
    print(f"wrote {target} ({target.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    build(sys.argv[1])
