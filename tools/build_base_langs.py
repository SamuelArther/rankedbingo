"""Builds lang/bases-<code>.js from the translated lang/bases-<code>.json files.

lang/bases-en.json lists the English installation descriptions and location
names (exported from js/bases-data.js); each translation maps those English
strings to the language. Missing strings fall back to English at runtime, so
they're reported, not fatal. Usage: python tools/build_base_langs.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LANG_DIR = ROOT / "lang"


def export_english():
    """Rewrites lang/bases-en.json from the current js/bases-data.js."""
    text = (ROOT / "js" / "bases-data.js").read_text(encoding="utf-8")
    bases = json.loads(re.search(r"window\.BASES = (\[.*\]);", text, re.S).group(1))
    english = {
        "descriptions": sorted({b["d"] for b in bases}),
        "locations": sorted({b["loc"] for b in bases}),
    }
    (LANG_DIR / "bases-en.json").write_text(json.dumps(english, ensure_ascii=False, indent=1), encoding="utf-8")
    return english["descriptions"] + english["locations"]


def main():
    english = export_english()
    for path in sorted(LANG_DIR.glob("bases-*.json")):
        code = path.stem[len("bases-"):]
        if code == "en":
            continue
        data = json.loads(path.read_text(encoding="utf-8"))
        good = {k: data[k] for k in english if isinstance(data.get(k), str) and data[k].strip() and data[k] != k}
        missing = sum(1 for k in english if k not in data)
        body = json.dumps(good, ensure_ascii=False, separators=(",", ":"))
        (LANG_DIR / f"bases-{code}.js").write_text(
            f'"use strict";\n// Generated by tools/build_base_langs.py from lang/bases-{code}.json. Do not edit by hand.\n'
            f"window.BASES_TR = {body};\n",
            encoding="utf-8",
        )
        print(f"bases-{code}: {len(good)} translated, {missing} missing")


if __name__ == "__main__":
    main()
