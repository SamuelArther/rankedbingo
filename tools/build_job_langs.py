"""Builds lang/jobs-<code>.js from the translated lang/jobs-<code>.json files.

Each translation must have the same branches and job ids as js/jobs-data.js.
Jobs or fields that are missing fall back to English at runtime, so they're
reported, not fatal. Usage: python tools/build_job_langs.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LANG_DIR = ROOT / "lang"
FIELDS = ("title", "category", "description", "training")


def load_jobs():
    text = (ROOT / "js" / "jobs-data.js").read_text(encoding="utf-8")
    body = re.search(r"window\.FULL_JOBS = (\{.*\});", text, re.S).group(1)
    return json.loads(body)


def main():
    jobs = load_jobs()
    for path in sorted(LANG_DIR.glob("jobs-*.json")):
        code = path.stem[len("jobs-"):]
        if code == "en":
            continue
        data = json.loads(path.read_text(encoding="utf-8"))
        out, missing = {}, 0
        for branch, items in jobs.items():
            tr = data.get(branch, {})
            out[branch] = {}
            for job in items:
                t = tr.get(job["id"])
                if not t:
                    missing += 1
                    continue
                fields = {f: t[f] for f in FIELDS if isinstance(t.get(f), str) and t[f].strip() and t[f] != job.get(f)}
                if fields:
                    out[branch][job["id"]] = fields
        body = json.dumps(out, ensure_ascii=False, separators=(",", ":"))
        (LANG_DIR / f"jobs-{code}.js").write_text(
            f'"use strict";\n// Generated by tools/build_job_langs.py from lang/jobs-{code}.json. Do not edit by hand.\n'
            f"window.FULL_JOBS_TR = {body};\n",
            encoding="utf-8",
        )
        print(f"jobs-{code}: {sum(len(v) for v in out.values())} translated, {missing} missing")


if __name__ == "__main__":
    main()
