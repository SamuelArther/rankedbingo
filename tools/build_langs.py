"""Builds lang/<code>.js from the translated lang/<code>.json files.

Checks each translation against lang/en.json: every placeholder like {branch}
must survive. Strings missing from a translation fall back to English at
runtime, so they're reported, not fatal. Usage: python tools/build_langs.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LANG_DIR = ROOT / "lang"
PLACEHOLDER = re.compile(r"\{(\w+)\}")


def main():
    english = json.loads((LANG_DIR / "en.json").read_text(encoding="utf-8"))
    for path in sorted(LANG_DIR.glob("*.json")):
        code = path.stem
        if code == "en" or code.startswith(("jobs-", "bases-")):
            continue
        data = json.loads(path.read_text(encoding="utf-8"))
        good, bad = {}, []
        for key in english:
            value = data.get(key)
            if not isinstance(value, str) or not value.strip():
                continue
            if set(PLACEHOLDER.findall(key)) != set(PLACEHOLDER.findall(value)):
                bad.append(key)
                continue
            if value != key:
                good[key] = value
        missing = [k for k in english if k not in data]
        body = json.dumps(good, ensure_ascii=False, separators=(",", ":"))
        (LANG_DIR / f"{code}.js").write_text(
            f'"use strict";\n// Generated by tools/build_langs.py from lang/{code}.json. Do not edit by hand.\n'
            f"window.I18N_DATA = {body};\n",
            encoding="utf-8",
        )
        print(f"{code}: {len(good)} translated, {len(missing)} missing, {len(bad)} with broken placeholders"
              + (f" e.g. {bad[:2]}" if bad else ""))


if __name__ == "__main__":
    main()
